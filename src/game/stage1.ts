function aimed(cadenceTicks: number, count: number, speed: number, spreadRadians = 0.5) {
  return {
    kind: 'spread' as const,
    cadenceTicks,
    warmupTicks: 45,
    count,
    speed,
    spreadRadians,
    radius: 4,
    lifetimeTicks: 360,
  }
}

function wave(id: string, enemies: StageWaveDefinition['enemies']): StageWaveDefinition {
  return { id, enemies }
}

